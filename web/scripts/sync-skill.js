// Copies skills/bruh/SKILL.md into web/api/_skill.js so the serverless
// function can ship without reaching outside web/. Run: npm run sync
import { readFile, writeFile } from 'node:fs/promises';
const raw = await readFile(new URL('../../skills/bruh/SKILL.md', import.meta.url), 'utf8');
const body = raw.replace(/^---\n[\s\S]*?\n---\n/, '').trim();
await writeFile(new URL('../api/_skill.js', import.meta.url),
  `// GENERATED by scripts/sync-skill.js from skills/bruh/SKILL.md. Do not edit.\nexport const SKILL = ${JSON.stringify(body)};\n`);
console.log('synced SKILL.md -> api/_skill.js');
